local json = require('src/core/json')
local ini = require('src/core/ini')
local csv = require('src/core/csv')
local fx = require('helpers/fixtures')
local sim = require('helpers/sim')

describe('json', function()
  it('decodes rules.json with comments', function()
    local rules = json.decode(fx.read(fx.APP .. 'rules.json'))
    assert.is_table(rules.symptoms)
    assert.is_true(#rules.symptoms >= 11)
  end)

  it('round-trips nested data', function()
    local data = { a = 1, b = { 1, 2, 3 }, c = { d = 'x"y', e = true }, f = 1.5 }
    assert.same(data, json.decode(json.encode(data, true)))
    assert.same(data, json.decode(json.encode(data)))
  end)

  it('reports errors with a position', function()
    local ok, err = pcall(json.decode, '{"a": }')
    assert.is_false(ok)
    assert.matches('line 1', err)
  end)
end)

describe('ini', function()
  it('parses sections in order and ignores comments', function()
    local p = ini.parse('; header\n[B]\nVALUE=3 ; note\n[A]\nX = 1\n')
    assert.same({ 'B', 'A' }, p.order)
    assert.equals('3', p.sections.B.values.VALUE)
    assert.equals(1, ini.get(p, 'A', 'X', 0))
  end)

  it('serializes back to the same values', function()
    local text = fx.read(fx.ROOT .. 'cars/test_drift/current_setup.ini')
    local p = ini.parse(text)
    local again = ini.parse(ini.serialize(p, 'made by a test'))
    assert.same(p.order, again.order)
    assert.equals('30', again.sections.PRESSURE_LR.values.VALUE)
  end)

  it('converts CSP INIConfig sections', function()
    local p = ini.fromCspSections({ ARB_REAR = { MIN = { '0' }, MAX = { '10' } } })
    assert.equals('10', p.sections.ARB_REAR.values.MAX)
  end)
end)

describe('csv', function()
  it('round-trips samples', function()
    local samples = sim.scenarios.good()
    local back = csv.decode(csv.encode(samples))
    assert.equals(#samples, #back)
    assert.near(samples[100].slip, back[100].slip, 1e-3)
    assert.near(samples[100].pressureRR, back[100].pressureRR, 1e-3)
  end)
end)
